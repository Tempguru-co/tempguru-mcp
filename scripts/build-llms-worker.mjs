// Build the apex llms.txt Cloudflare Worker from repository-controlled files.
// scripts/build-okf.mjs generates both sources from the canonical facts, data,
// and skills before this script embeds them. No live fetch or prior Worker
// snapshot participates in the build.
//
//   node scripts/build-llms-worker.mjs
//   node scripts/build-llms-worker.mjs --from-committed  # compatibility alias

import { readFileSync, writeFileSync } from "node:fs";
import { SKILLS } from "./gen-skill-digests.mjs";

const allowedArgs = new Set(["--from-committed"]);
for (const arg of process.argv.slice(2)) {
  if (!allowedArgs.has(arg)) throw new Error(`unsupported argument: ${arg}`);
}

const publicFacts = JSON.parse(readFileSync("content/public-facts.json", "utf8"));
const policies = JSON.parse(readFileSync("content/mcp-data/policies.json", "utf8"));
const agent5Offer = policies.policies.find((policy) => policy.topic === "offers");
const agent5Terms = agent5Offer?.confirmed_claims?.[0];
if (
  agent5Offer?.confirmed_claims?.length !== 1 ||
  agent5Offer?.code !== "AGENT5" ||
  agent5Offer?.discount_percent !== 5 ||
  agent5Offer?.cap_usd !== 500 ||
  agent5Offer?.expires !== "2026-12-31" ||
  agent5Offer?.scope !== "first order, new clients" ||
  !agent5Terms
) {
  throw new Error("canonical AGENT5 offer record is missing or incomplete");
}
const okfDiscovery = JSON.parse(
  readFileSync("public/.well-known/okf.json", "utf8"),
);
const FILES = {
  "/llms.txt": readFileSync("public/llms.txt", "utf8"),
  "/llms-full.txt": readFileSync("public/llms-full.txt", "utf8"),
};

const errors = [];
const emDash = "\u2014";
for (const [path, body] of Object.entries(FILES)) {
  if (body.length < 1_000) errors.push(`${path}: empty or unexpectedly short`);
  if (body.includes(emDash)) errors.push(`${path}: em-dash remains`);
  if (!body.includes(publicFacts.catalog.markets.publicDescription)) {
    errors.push(`${path}: canonical market qualification is missing`);
  }
  if (!body.includes(agent5Terms)) {
    errors.push(`${path}: canonical AGENT5 offer terms are missing`);
  }
  for (const claim of Object.values(publicFacts.withheldClaims)) {
    for (const phrase of claim.blockedPhrases) {
      if (body.toLowerCase().includes(phrase.toLowerCase())) {
        errors.push(`${path}: withheld claim remains: ${phrase}`);
      }
    }
  }
  for (const required of [
    publicFacts.agentInterfaces.mcp.url,
    publicFacts.agentInterfaces.a2a.url,
    "https://tempguru.co/.well-known/agent-card.json",
    "https://tempguru.co/.well-known/tempguru-facts.json",
    "https://tempguru.co/auth.md",
    "Open Knowledge Format",
    "buyer-operated",
  ]) {
    if (!body.includes(required)) errors.push(`${path}: missing ${required}`);
  }
  const inventories = [
    ...body.matchAll(/^- Canonical Agent Skills \((\d+)\):[^\n]*$/gm),
  ];
  if (
    inventories.length !== 1 ||
    Number(inventories[0]?.[1]) !== SKILLS.length ||
    SKILLS.some((skill) => !inventories[0]?.[0].includes(skill))
  ) {
    errors.push(`${path}: canonical ${SKILLS.length}-skill inventory is stale`);
  }
  const mcpInventory =
    body.match(
      /^- MCP Server[^\n]*https:\/\/mcp\.tempguru\.co\/mcp[^\n]*$/gm,
    ) ?? [];
  if (
    mcpInventory.length !== 1 ||
    !mcpInventory[0].includes("12 tools") ||
    !mcpInventory[0].includes("save_staffing_plan") ||
    !mcpInventory[0].includes("2026-07-28") ||
    !mcpInventory[0].includes("2025-era compatibility") ||
    !mcpInventory[0].includes("complete plan has no plan_id") ||
    !mcpInventory[0].includes("never duplicate")
  ) {
    errors.push(`${path}: canonical dual-era Phase A MCP inventory is stale`);
  }
}

const fullMarkers = FILES["/llms-full.txt"].match(
  /^## Included document: \/okf\//gm,
) ?? [];
if (
  FILES["/llms-full.txt"] === FILES["/llms.txt"] ||
  FILES["/llms-full.txt"].length < FILES["/llms.txt"].length * 5
) {
  errors.push("/llms-full.txt must be a materially expanded knowledge export");
}
if (fullMarkers.length !== okfDiscovery.bundle.file_count) {
  errors.push(
    `/llms-full.txt contains ${fullMarkers.length} OKF documents; expected ${okfDiscovery.bundle.file_count}`,
  );
}
for (const requiredPath of [
  "/okf/index.md",
  "/okf/rate-index.md",
  "/okf/workflows/event-staffing-ordering.md",
]) {
  if (!FILES["/llms-full.txt"].includes(`Included document: ${requiredPath}`)) {
    errors.push(`/llms-full.txt: missing ${requiredPath}`);
  }
}

if (errors.length) {
  console.error("llms Worker validation failed:");
  for (const error of errors) console.error(`  - ${error}`);
  process.exit(1);
}

const output =
  `// TempGuru llms.txt worker. Serves /llms.txt and /llms-full.txt at the apex.\n` +
  `// Generated by scripts/build-llms-worker.mjs from public/llms*.txt.\n\n` +
  `const FILES = ${JSON.stringify(FILES, null, 2)};\n\n` +
  `const STATIC_SECURITY_HEADERS = {\n` +
  `  "x-content-type-options": "nosniff",\n` +
  `  "content-security-policy": "default-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'"\n` +
  `};\n\n` +
  `export default {\n` +
  `  async fetch(request) {\n` +
  `    const url = new URL(request.url);\n` +
  `    const body = FILES[url.pathname];\n` +
  `    if (body) {\n` +
  `      return new Response(body, {\n` +
  `        headers: {\n` +
  `          ...STATIC_SECURITY_HEADERS,\n` +
  `          "content-type": "text/plain; charset=utf-8",\n` +
  `          "access-control-allow-origin": "*",\n` +
  `          "cache-control": "public, max-age=3600"\n` +
  `        }\n` +
  `      });\n` +
  `    }\n` +
  `    return fetch(request);\n` +
  `  },\n` +
  `};\n`;

writeFileSync("cloudflare/llms-worker.js", output);
console.log(`Wrote cloudflare/llms-worker.js (${output.length} bytes)`);
console.log("  source: canonical generated public/llms*.txt");
console.log(
  `  /llms.txt: ${FILES["/llms.txt"].length}b | ` +
    `/llms-full.txt: ${FILES["/llms-full.txt"].length}b ` +
    `(${fullMarkers.length} OKF documents)`,
);
